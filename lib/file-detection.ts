/**
 * Detect programming language from file path
 */
export function detectLanguage(path: string): string | null {
  const filename = path.split("/").pop() || "";

  // Check exact filename match first
  if (FILENAME_TO_LANGUAGE[filename]) {
    return FILENAME_TO_LANGUAGE[filename];
  }

  // Check extension
  for (const [ext, lang] of Object.entries(EXTENSION_TO_LANGUAGE)) {
    if (filename.endsWith(ext)) {
      return lang;
    }
  }

  return null;
}

/**
 * Common ignore patterns for directories/files
 */
const IGNORE_PATTERNS = [
  "node_modules/",
  ".git/",
  "dist/",
  "build/",
  "__pycache__/",
  ".venv/",
  "venv/",
  "env/",
  ".next/",
  ".nuxt/",
  "target/",
  "bin/",
  "obj/",
  ".idea/",
  ".vscode/",
  "*.min.js",
  "*.min.css",
  "package-lock.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "*.log",
  "*.tsbuildinfo",
];

/**
 * Check if a path matches common ignore patterns
 */
export function isIgnoredPath(path: string): boolean {
  // Check exact pattern matches
  for (const pattern of IGNORE_PATTERNS) {
    if (matchPattern(path, pattern)) {
      return true;
    }
    // Check parent directories
    const parts = path.split("/");
    for (let i = 1; i <= parts.length; i++) {
      const parent = parts.slice(0, i).join("/");
      if (matchPattern(parent, pattern)) {
        return true;
      }
    }
  }
  return false;
}

function matchPattern(path: string, pattern: string): boolean {
  // Simple glob matching
  const regexPattern = pattern
    .replace(/\./g, "\\.")
    .replace(/\*/g, ".*")
    .replace(/\?/g, ".");
  const regex = new RegExp(`^${regexPattern}$`);
  return regex.test(path);
}

/**
 * Heuristics to detect generated files
 */
export function isGeneratedFile(path: string, content?: string): boolean {
  const generatedPatterns = [
    // Minified files
    /\.min\.(js|css)$/,
    // Bundle files
    /bundle\.(js|css)$/,
    /vendor\.(js|css)$/,
    // Generated by build tools
    /\.g\.py$/,
    /_pb2\.py$/,
    /_grpc\.py$/,
    // TypeScript generated
    /\.d\.ts$/,
    // Protobuf generated
    /_pb2\.py$/,
    // Lock files
    /^package-lock\.json$/,
    /^yarn\.lock$/,
    /^pnpm-lock\.yaml$/,
    /^Cargo\.lock$/,
    /^go\.sum$/,
    /^composer\.lock$/,
    /^poetry\.lock$/,
    // IDE/OS
    /^\.DS_Store$/,
    /^Thumbs\.db$/,
  ];

  for (const pattern of generatedPatterns) {
    if (pattern.test(path)) {
      return true;
    }
  }

  // Check content for generated headers
  if (content) {
    const generatedHeaders = [
      "// Generated by",
      "/* Generated by",
      "# Generated by",
      "# Auto-generated",
      "// Auto-generated",
      "/* Auto-generated",
      "<auto-generated>",
      "/// <auto-generated>",
      "DO NOT EDIT",
      "do not edit",
      "autogenerated",
      "auto-generated",
    ];
    const contentLower = content.toLowerCase();
    for (const header of generatedHeaders) {
      if (contentLower.includes(header.toLowerCase())) {
        return true;
      }
    }
  }

  return false;
}

/**
 * Check if content appears to be binary
 */
export function isBinaryContent(content?: string): boolean {
  if (!content) return true;

  // Check for null bytes
  if (content.includes("\x00")) return true;

  // Check ratio of printable characters
  const printable = Array.from(content).filter(
    (c) => c.charCodeAt(0) >= 32 || c === "\n" || c === "\r" || c === "\t"
  ).length;

  if (content.length > 0 && printable / content.length < 0.7) {
    return true;
  }

  return false;
}

/**
 * Format file size to human-readable string
 */
export function formatFileSize(bytes: number): string {
  if (bytes === 0) return "0 B";

  const units = ["B", "KB", "MB", "GB", "TB"];
  const i = Math.floor(Math.log(bytes) / Math.log(1024));
  const size = bytes / Math.pow(1024, i);

  return `${size.toFixed(i === 0 ? 0 : 1)} ${units[i]}`;
}

/**
 * Extract file metadata from TreeNode
 */
export interface FileMetadata {
  path: string;
  name: string;
  extension: string;
  size: number;
  sizeFormatted: string;
  language: string | null;
  isBinary: boolean;
  isGenerated: boolean;
  isIgnored: boolean;
}

export function extractFileMetadata(node: {
  path: string;
  size?: number;
  language?: string;
  is_binary?: boolean;
  is_generated?: boolean;
  is_ignored?: boolean;
}): FileMetadata {
  const name = node.path.split("/").pop() || "";
  const extension = name.includes(".") ? name.slice(name.lastIndexOf(".")) : "";

  return {
    path: node.path,
    name,
    extension,
    size: node.size || 0,
    sizeFormatted: formatFileSize(node.size || 0),
    language: node.language || detectLanguage(node.path),
    isBinary: node.is_binary || false,
    isGenerated: node.is_generated || false,
    isIgnored: node.is_ignored || false,
  };
}